import {test,expect} from '@playwright/test'
const fixture=JSON.parse(process.env.B2_BROWSER_FIXTURE??'{}')
test('real administrative profile edit and tenant state changes persist with revoked sessions',async({page,context})=>{
 await context.addCookies([
  {name:'__Host-cleanops_session',value:'c'.repeat(43),url:'https://127.0.0.1:3443',httpOnly:true,secure:true,sameSite:'Lax'},
  {name:'__Host-cleanops_csrf',value:'e'.repeat(43),url:'https://127.0.0.1:3443',secure:true,sameSite:'Lax'},
 ])
 await page.goto('/administration/users')
 await page.getByRole('button',{name:'Continuar con mi sesión'}).click()
 const table=page.getByRole('table',{name:'Usuarios visibles para tu sesión en esta empresa'})
 await table.getByRole('button',{name:'Ver ficha de '+fixture.targetName}).click()
 const dialog=page.getByRole('dialog',{name:'Ficha de usuario'})
 await dialog.getByRole('textbox',{name:'Nombre del usuario',exact:true}).fill('B2 browser edited user')
 await dialog.getByRole('textbox',{name:'Motivo de edición'}).fill('B2 browser profile edit')
 await dialog.getByRole('button',{name:'Guardar perfil'}).click()
 await expect(dialog).not.toBeVisible()
 await expect(table.getByText('B2 browser edited user')).toBeVisible()
 await table.getByRole('button',{name:'Ver ficha de B2 browser edited user'}).click()
 await dialog.getByRole('button',{name:'Desactivar acceso en esta empresa'}).click()
 await dialog.getByRole('textbox',{name:'Motivo del cambio de estado'}).fill('B2 browser membership disable')
 await dialog.getByRole('button',{name:'Confirmar desactivación'}).click()
 await expect(dialog).not.toBeVisible()
 const row=table.getByRole('row').filter({hasText:'B2 browser edited user'})
 await expect(row.getByText('Desactivado',{exact:true})).toBeVisible()
 const oldSession=()=>context.request.get('/auth/users/session',{headers:{cookie:'__Host-cleanops_session='+'a'.repeat(43)+'; __Host-cleanops_csrf='+'e'.repeat(43)}})
 expect((await oldSession()).status()).toBe(401)
 await row.getByRole('button',{name:'Ver ficha de B2 browser edited user'}).click()
 await dialog.getByRole('button',{name:'Reactivar acceso en esta empresa'}).click()
 await dialog.getByRole('textbox',{name:'Motivo del cambio de estado'}).fill('B2 browser membership enable')
 await dialog.getByRole('button',{name:'Confirmar reactivación'}).click()
 await expect(dialog).not.toBeVisible()
 await expect(row.getByText('Activo',{exact:true})).toBeVisible()
 expect((await oldSession()).status()).toBe(401)
 const other=await context.request.get('/auth/users/session',{headers:{cookie:'__Host-cleanops_session='+'d'.repeat(43)+'; __Host-cleanops_csrf='+'e'.repeat(43)}})
 expect(other.status()).toBe(200)
 expect((await other.json()).data.tenant_id).toBe(fixture.otherTenant)
 await page.screenshot({path:'artifacts/b2-users/profile-and-state.png'})
})
