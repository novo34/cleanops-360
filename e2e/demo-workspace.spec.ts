for (const width of [390, 768, 1440]) {
  test('responsive navigation and zero horizontal overflow at ' + width, async ({ page }) => {
    await page.setViewportSize({ width, height: 960 })
    for (const path of ['/demo', '/demo/empresas', '/demo/clientes', '/demo/empleados', '/demo/planning']) {
      await page.goto(path)
      await expect(page.locator('h1')).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
      if (width !== 768) await page.screenshot({ path: 'test-results/demo-' + (path.split('/')[2] ?? 'dashboard') + '-' + width + '.png', fullPage: true })
    }
    if (width === 390) {
      await page.getByRole('button', { name: 'Abrir navegación' }).click()
      await expect(page.getByRole('navigation', { name: 'Navegación principal' })).toBeVisible()
      await page.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Clientes', exact: true }).click()
      await expect(page.getByRole('heading', { name: 'Clientes', exact: true })).toBeVisible()
    }
  })
}
